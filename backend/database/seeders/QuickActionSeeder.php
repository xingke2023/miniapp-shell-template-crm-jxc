    /**
     * 批量建一个行业的多个 menu 分组按钮 + prompt 子项。
     *
     * @param  array<int,array{0:string,1:string,2:string,3:int,4:array<int,array{0:string,1:string,2:string,3:string}>}>  $menus
     */
    private function buildIndustryMenus(string $industry, array $menus): void
    {
        $templateId = MenuTemplate::query()
            ->where('industry', $industry)
            ->where('is_active', true)
            ->value('id');

        foreach ($menus as [$key, $emoji, $label, $sortOrder, $items]) {
            $menu = QuickAction::create([
                'key' => $key,
                'emoji' => $emoji,
                'label' => $label,
                'action_type' => 'menu',
                'industry' => $industry,
                'menu_template_id' => $templateId,
                'sort_order' => $sortOrder,
            ]);

            $sort = 10;
            foreach ($items as [$iEmoji, $iLabel, $iDesc, $iPrompt]) {
                $menu->items()->create([
                    'emoji' => $iEmoji,
                    'label' => $iLabel,
                    'desc' => $iDesc,
                    'item_type' => 'prompt',
                    'prompt' => $iPrompt,
                    'sort_order' => $sort,
                ]);
                $sort += 10;
            }
        }
    }
