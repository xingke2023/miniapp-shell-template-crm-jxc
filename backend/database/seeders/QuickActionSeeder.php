    /**
     * 建一个 menu 类型分组按钮 + 其子菜单项。
     *
     * @param  array{0:string,1:string,2:array<int,array{0:string,1:string,2:string,3:string}>}  $group
     */
    private function createIndustryMenu(string $slug, string $key, array $group, int $sortOrder): void
    {
        [$emoji, $label, $items] = $group;

        $menu = QuickAction::create([
            'key' => $key,
            'emoji' => $emoji,
            'label' => $label,
            'action_type' => 'menu',
            'industry' => $slug,
            'sort_order' => $sortOrder,
        ]);

        $sort = 10;
        foreach ($items as [$iEmoji, $iLabel, $iDesc, $iPrompt]) {
            $menu->items()->create([
                'emoji' => $iEmoji,
                'label' => $iLabel,
                'desc' => $iDesc,
                'item_type' => 'prompt',
                'prompt' => $iPrompt,
                'sort_order' => $sort,
            ]);
            $sort += 10;
        }
    }

